"""Turn the policy (ONNX) into policy_model.[ch], the weights the firmware compiles in.

  uv run firmware/policy/export.py                    # OnePolicy.onnx
  uv run firmware/policy/export.py path/to/policy.onnx

The ONNX must be an rsl_rl actor as OnePolicy exports it: obs -> Sub(mean) ->
Div(std + eps) -> Gemm/Elu ... -> Gemm -> actions. The weights become float32
const arrays in flash; the CRC32 over them is what the board reports.
"""

import argparse
import zlib
from pathlib import Path

import numpy as np
import onnx
from onnx import numpy_helper

HERE = Path(__file__).resolve().parent
# Flash left for the weights: 1 MB minus the vector table and ~60 kB of code.
FLASH_BUDGET = 0xF0000


def load_actor(path: Path) -> tuple[np.ndarray, np.ndarray, list[tuple[np.ndarray, np.ndarray]]]:
  """(mean, denom, [(W [out][in], b), ...]) from the ONNX graph, checking its shape."""
  graph = onnx.load(str(path)).graph
  init = {t.name: numpy_helper.to_array(t).astype(np.float32) for t in graph.initializer}
  ops = [n.op_type for n in graph.node]
  hidden = (len(ops) - 3) // 2
  if ops[:2] != ["Sub", "Div"] or ops[2:] != ["Gemm", "Elu"] * hidden + ["Gemm"]:
    raise ValueError(f"{path}: expected Sub, Div, (Gemm, Elu)*, Gemm; got {ops}")
  mean = init[graph.node[0].input[1]].ravel()
  denom = init[graph.node[1].input[1]].ravel()
  layers = []
  for node in graph.node[2:]:
    attrs = {a.name: onnx.helper.get_attribute_value(a) for a in node.attribute}
    if node.op_type == "Elu" and attrs.get("alpha", 1.0) != 1.0:
      raise ValueError("The firmware implements ELU with alpha = 1.")
    if node.op_type == "Gemm":
      if attrs.get("transB", 0) != 1 or attrs.get("alpha", 1.0) != 1.0 or attrs.get("beta", 1.0) != 1.0:
        raise ValueError(f"Unsupported Gemm attributes {attrs}.")
      layers.append((init[node.input[1]], init[node.input[2]]))
  return mean, denom, layers


def _c_array(name: str, a: np.ndarray) -> str:
  values = [float(v).hex() + "f" for v in a.ravel()]  # hex floats are exact
  lines = [", ".join(values[i:i + 8]) for i in range(0, len(values), 8)]
  return f"const float {name}[{len(values)}] = {{\n    " + ",\n    ".join(lines) + "\n};\n"


def export(onnx_path: Path, out_dir: Path) -> None:
  mean, denom, layers = load_actor(onnx_path)
  arrays = [mean, denom] + [a for layer in layers for a in layer]
  nbytes = sum(a.nbytes for a in arrays)
  if nbytes > FLASH_BUDGET:
    raise ValueError(f"Policy is {nbytes} bytes, the MCXN236 has room for {FLASH_BUDGET} in flash.")
  crc = 0
  for a in arrays:
    crc = zlib.crc32(np.ascontiguousarray(a).tobytes(), crc)
  n_obs, n_act = layers[0][0].shape[1], layers[-1][0].shape[0]
  dims = [n_obs] + [w.shape[0] for w, _ in layers]

  header = (
    "/* Generated by firmware/policy/export.py; do not edit. */\n"
    f"/* Source: {onnx_path.name} */\n"
    "#ifndef POLICY_MODEL_H_\n#define POLICY_MODEL_H_\n\n"
    '#include "policy_net.h"\n\n'
    f"#define POLICY_MODEL_CRC  0x{crc:08X}U\n"
    f"#define POLICY_N_OBS      {n_obs}U\n"
    f"#define POLICY_N_ACT      {n_act}U\n"
    f"#define POLICY_N_LAYERS   {len(layers)}U\n"
    f"#define POLICY_MAX_WIDTH  {max(dims)}U\n\n"
    "extern const float POLICY_OBS_MEAN[POLICY_N_OBS];\n"
    "extern const float POLICY_OBS_DENOM[POLICY_N_OBS];\n"
    "extern const policy_layer_t POLICY_LAYERS[POLICY_N_LAYERS];\n\n"
    "#endif /* POLICY_MODEL_H_ */\n"
  )
  body = [
    "/* Generated by firmware/policy/export.py; do not edit. */\n",
    '#include "policy_model.h"\n\n',
    "/* Observation normalizer: x_norm = (x - mean) / denom, denom = std + eps */\n",
    _c_array("POLICY_OBS_MEAN", mean),
    _c_array("POLICY_OBS_DENOM", denom),
  ]
  for i, (w, b) in enumerate(layers):
    body.append(f"\n/* Layer {i}: {w.shape[1]} -> {w.shape[0]}, weights [out][in] */\n")
    body.append(_c_array(f"L{i}_W", w))
    body.append(_c_array(f"L{i}_B", b))
  body.append("\nconst policy_layer_t POLICY_LAYERS[POLICY_N_LAYERS] = {\n")
  for i, (w, _) in enumerate(layers):
    body.append(f"    {{L{i}_W, L{i}_B, {w.shape[1]}U, {w.shape[0]}U}},\n")
  body.append("};\n")
  (out_dir / "policy_model.h").write_text(header)
  (out_dir / "policy_model.c").write_text("".join(body))
  print(f"{onnx_path.name} -> {out_dir}/policy_model.[ch]: {' -> '.join(map(str, dims))}, "
        f"{nbytes / 1024:.0f} kB, CRC 0x{crc:08X}")


def main():
  parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
  parser.add_argument("onnx", type=Path, nargs="?", default=HERE / "OnePolicy.onnx")
  parser.add_argument("--out", type=Path, default=HERE)
  args = parser.parse_args()
  export(args.onnx, args.out)


if __name__ == "__main__":
  main()
